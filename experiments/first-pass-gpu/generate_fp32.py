"""Instantiate the exact scalar algorithms in FP32, without a second source fork."""
from pathlib import Path
import re
import sys

source = Path(__file__).resolve().parent
output = Path(sys.argv[1])
output.mkdir(parents=True, exist_ok=True)
files = {"blend.hpp": "float_blend.hpp", "solver.hpp": "float_solver.hpp", "warp.cuh": "float_warp.cuh"}
for original in sys.argv[2:] or files:
    generated = files[original]
    text = (source / original).read_text()
    text = re.sub(r"\bdouble\b", "float", text)
    text = re.sub(r"\bfirstpass\b", "firstpass32", text)
    # Keep every floating constant in FP32 too, so promotion cannot retain
    # FP64 arithmetic in the generated device implementation.
    text = re.sub(r"(?<![\w.])((?:\d+\.\d*|\.\d+|\d+[eE][+-]?\d+)(?:[eE][+-]?\d+)?)(?![\w.])", r"\1f", text)
    for before, after in files.items():
        text = text.replace('"' + before + '"', '"' + after + '"')
    (output / generated).write_text("// Generated by generate_fp32.py; edit the original sources.\n" + text)
